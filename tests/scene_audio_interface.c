/* ---- Shared guest memory helpers --------------------------------------- */

static uint8_t *map_guest(Guest *g, uint32_t addr, uint32_t width) {
    if (addr >= SCRATCH_BASE && addr <= SCRATCH_BASE + SCRATCH_SIZE - width)
        return g->scratch + (addr - SCRATCH_BASE);
    assert(addr <= EE_RAM_SIZE - width);
    return g->ee + addr;
}

static uint32_t guest_load(void *user, uint32_t addr, uint32_t width) {
    Guest *g = user;
    assert(width == 1 || width == 2 || width == 4);
    uint8_t *p = map_guest(g, addr, width);
    uint32_t v = 0;
    for (uint32_t i = 0; i < width; ++i)
        v |= (uint32_t)p[i] << (8 * i);
    return v;
}

static void guest_store(void *user, uint32_t addr, uint32_t width, uint32_t value) {
    Guest *g = user;
    assert(width == 1 || width == 2 || width == 4);
    uint8_t *p = map_guest(g, addr, width);
    for (uint32_t i = 0; i < width; ++i)
        p[i] = (uint8_t)(value >> (8 * i));
}

static uint8_t audio_r8(void *ctx, uint32_t a) { return (uint8_t)guest_load(ctx, a, 1); }
static uint16_t audio_r16(void *ctx, uint32_t a) { return (uint16_t)guest_load(ctx, a, 2); }
static uint32_t audio_r32(void *ctx, uint32_t a) { return guest_load(ctx, a, 4); }
static void audio_w8(void *ctx, uint32_t a, uint8_t v) { guest_store(ctx, a, 1, v); }
static void audio_w16(void *ctx, uint32_t a, uint16_t v) { guest_store(ctx, a, 2, v); }
static void audio_w32(void *ctx, uint32_t a, uint32_t v) { guest_store(ctx, a, 4, v); }

/* ---- IOP & SPU2 callbacks for HGAudioIop ------------------------------- */

static bool iop_read(void *ctx, uint32_t src, uint8_t *out, size_t size) {
    Guest *g = ctx;
    if (src < IOP_WINDOW_BASE) return false;
    uint32_t off = src - IOP_WINDOW_BASE;
    if (off > g->iop_alloc_size || size > g->iop_alloc_size - off)
        return false;
    memcpy(out, g->iop_heap + off, size);
    return true;
}

static void spu_write16(void *ctx, uint32_t addr, uint16_t val) {
    Guest *g = ctx;
    assert(g->spu_write_count < sizeof(g->spu_writes) / sizeof(*g->spu_writes));
    g->spu_writes[g->spu_write_count++] = (SpuWrite){addr, val};
}

static void spu_voice_transfer(void *ctx, uint32_t core, uint32_t mode,
                               uint32_t src, uint32_t dest, uint32_t size) {
    Guest *g = ctx;
    assert(core == 0 && mode == 0 && src == IOP_WINDOW_BASE && dest > 0 && size > 0);
    g->spu_dma_count++;
}

/* ---- Audio bus external seam handler (SIF + SG2 bank hooks) ------------ */

static uint32_t audio_call(void *ctx, uint32_t target,
                           uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3,
                           uint32_t t0) {
    Guest *g = ctx;
    (void)a3;
    (void)t0;
    switch (target) {
    case HG_X_INTS_OFF:
    case HG_X_INTS_ON:
    case HG_X_FLUSHCACHE:
    case 0x002a9050:
    case 0x002a9180:
    case 0x002a9d70:
        return 0;
    case HG_X_SIF_ALLOC:
        if (g->iop_alloc_size != 0 || a0 == 0 || a0 > IOP_HEAP_CAPACITY)
            return 0;
        memset(g->iop_heap, 0, a0);
        g->iop_alloc_size = a0;
        g->iop_allocs++;
        return IOP_WINDOW_BASE;
    case HG_X_SIF_FREE:
        assert(a0 == IOP_WINDOW_BASE && g->iop_alloc_size > 0 && !g->sif_dma_active);
        g->iop_alloc_size = 0;
        g->iop_frees++;
        return 0;
    case HG_X_SIF_SET_DMA: {
        uint32_t src = guest_load(g, a0 + 0, 4);
        uint32_t dest = guest_load(g, a0 + 4, 4);
        uint32_t size = guest_load(g, a0 + 8, 4);
        assert(a1 == 1 && size > 0 && !g->sif_dma_active);
        g->sif_dma_src = src;
        g->sif_dma_dest = dest;
        g->sif_dma_size = size;
        g->sif_dma_active = true;
        return ++g->sif_dma_handle;
    }
    case HG_X_SIF_DMA_STAT:
        if (g->sif_dma_active && a0 == g->sif_dma_handle) {
            assert(g->sif_dma_dest >= IOP_WINDOW_BASE);
            uint32_t off = g->sif_dma_dest - IOP_WINDOW_BASE;
            assert(off + g->sif_dma_size <= g->iop_alloc_size);
            memcpy(g->iop_heap + off, map_guest(g, g->sif_dma_src, g->sif_dma_size),
                   g->sif_dma_size);
            g->sif_dma_active = false;
        }
        return UINT32_MAX;
    case HG_SG2_UPLOAD_START:
    case HG_SG2_UPLOAD_POLL:
    case HG_SG2_BANK_BIND:
        if (!g->route_bank_calls)
            return 0; /* Negative control: disconnected bank-call routing. */
        return hg_audio_ee_bank_call(&g->audio_ee, target, a0, a1, a2);
    case HG_X_GLOBAL_TICK:
        return ++g->global_tick;
    case HG_X_TIME_A:
        return a0 * 300u;
    case HG_X_TIME_B:
        return a0 ^ (a1 >> 16);
    default:
        assert(!"unexpected audio bus external call");
        return 0;
    }
}

/* ---- Resource/Scene bus handler ---------------------------------------- */

static uint32_t scene_call_fp(void *user, uint32_t entry,
                              uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3,
                              uint32_t f12, uint32_t f13) {
    Guest *g = user;
    if (entry == 0x001564a0) {
        assert(g->voice_start_count < 16);
        g->voice_starts[g->voice_start_count++] =
            (RecordedCall){entry, a0, a1, a2, a3, f12, f13};
        return 0;
    }
    if (entry == 0x00182850) {
        g->glyph_draw_count++;
        return 16;
    }
    assert(!"unexpected call_fp entry");
    return 0;
}

