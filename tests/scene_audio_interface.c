/* Repeatable synthetic integration experiment verifying the scene-to-audio
 * interface boundary between M18/M19/M20/M21 producers and M22's SG2IOP audio
 * service on one shared EE guest bus.
 *
 * Explicitly separates:
 *   1. Scene-produced requests:
 *      - Resource loader (hg_pack_special_step) -> 00156a50 (bank registration).
 *      - Title menu (hg_title_menu)             -> 00156ad0 (SFX cue request).
 *      - Title scene / HGScript (hg_title_scene_call -> hg_script_timed_*)
 *                                               -> 001564a0 / 00156550 (stream
 *                                                  voice start/stop seam).
 *   2. Externally supplied metadata & resolved voice parameters:
 *      - Sound-ID descriptor (00157ed0 mapping id=4 -> group 0, idx 0, p1=1, p2=3).
 *      - Resolved physical voice, sample offset and HGSg2VoiceParams (since
 *        the EE sequence consumer 002ade94..002ae2c0 / 002a96b8 / 002ab508 and
 *        physical voice allocator remain unresolved).
 *   3. Operations executed by M22's audio service:
 *      - hg_audio_register_entry, hg_audio_ee_bank_call, hg_audio_ee_flush,
 *        hg_audio_iop_step_dma, hg_audio_play, hg_audio_ee_stage_play_voice,
 *        hg_audio_ee_stage_key, hg_audio_cancel, hg_audio_iop_destroy.
 *   4. Outputs generated by the host SPU2 model:
 *      - Ordered SPU2 register writes, ENVX replies, and stereo PCM from
 *        hg_audio_iop_render.
 */
