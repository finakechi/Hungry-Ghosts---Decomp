static uint32_t resource_call(void *user, uint32_t entry,
                              uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3);

static HGResourceEnv make_res_env(Guest *g) {
    return (HGResourceEnv){g, guest_load, guest_store, resource_call,
                           &g->read_state, &g->read_env};
}

static uint32_t resource_call(void *user, uint32_t entry,
                              uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3) {
    Guest *g = user;
    /* Loader -> M22 bank registration (00156a50). */
    if (entry == 0x00156a50)
        return hg_audio_register_entry(&g->audio_bus, a0);

    /* Extra register seam emitted before 00156ad0 by front_end.c (t0 = 1). */
    if (entry == HG_CALL_T_REGS) {
        g->pending_t0 = a0;
        return 0;
    }

    /* Scene/front-end SFX request (00156ad0). */
    if (entry == 0x00156ad0) {
        assert(g->sfx_request_count < 16);
        g->sfx_requests[g->sfx_request_count++] =
            (RecordedCall){entry, a0, a1, a2, a3, g->pending_t0, 0};
        g->pending_t0 = 0;
        return 0;
    }

    /* Voice stop request (00156550). */
    if (entry == 0x00156550) {
        assert(a0 == 1 && !a1 && !a2 && !a3);
        g->voice_stop_count++;
        return 0;
    }

    /* Title scene entries routed through real hg_title_scene_call. */
    HGResourceEnv env = make_res_env(g);
    uint32_t result = 0;
    if (hg_title_scene_call(&env, &g->title_scene, entry, a0, &result))
        return result;

    /* Non-audio front-end / title scene external seams. */
    switch (entry) {
    case 0x00a87de0: /* card poll */
    case 0x00a87ed0: /* title alpha presentation */
    case 0x00198f60:
    case 0x0012c980:
    case 0x0013b6e0:
    case 0x001430a0:
    case 0x00143100:
    case 0x0018c520:
    case 0x00143150:
    case 0x001431a0:
    case 0x00182480:
    case 0x0013ce80:
    case 0x00137ac0:
    case 0x00139690:
    case 0x00167740:
    case 0x00265460:
    case 0x0025ddd0:
    case 0x0025ca90:
    case 0x00166770:
    case 0x00166910:
    case 0x00139010:
    case 0x00139040:
    case 0x001390b0:
    case 0x001404f0:
        return 0;
    default:
        assert(!"unexpected resource/scene bus call");
        return 0;
    }
}

/* ---- Synthetic SShd bank builder --------------------------------------- */

static void w16_le(uint8_t *buf, size_t off, uint16_t v) {
    buf[off] = (uint8_t)v;
    buf[off + 1] = (uint8_t)(v >> 8);
}

static void w32_le(uint8_t *buf, size_t off, uint32_t v) {
    for (unsigned i = 0; i < 4; ++i)
        buf[off + i] = (uint8_t)(v >> (8 * i));
}

/* Build a minimal 1-descriptor synthetic SShd resource with:
 * - Descriptor group 0 (SPU2 dest 0x5010), volume 0x7f.
 * - table4 (bank+0x1c -> offset 0x90) resolving (param1=1, param2=3),
 *   matching the authenticated title cursor sound ID 4 descriptor.
 * - 32-byte synthetic ADPCM payload:
 *   block 0 (offset 0x00): shift 12, loop flags 7 (start+repeat+end), nibbles +6/+6.
 *   block 1 (offset 0x10): shift 12, end flag 1 (no loop), nibbles +1/-2.
 */
static void build_synthetic_bank(uint8_t *out, uint32_t *out_size,
                                 uint8_t payload_out[32]) {
    const uint32_t bank_off = 0x30;
    const uint32_t bank_size = 0x100;
    const uint32_t payload_off = bank_off + bank_size;
    const uint32_t payload_size = 32;
    const uint32_t total = payload_off + payload_size;

    memset(out, 0, total);
    /* Resource header (0x20 bytes) + 1 descriptor (0x10 bytes). */
    w32_le(out, 0x00, total);
    w32_le(out, 0x04, bank_off);
    w32_le(out, 0x08, 0);            /* descriptor-table shift */
    w32_le(out, 0x0c, 1);            /* 1 descriptor */
    w32_le(out, 0x10, payload_off);  /* retained size */
    w32_le(out, 0x14, payload_size);
    w32_le(out, 0x18, payload_off);  /* payload start offset */
    w32_le(out, 0x1c, 0);
    /* Descriptor 0: payload_size, bank_offset, bank_group_id=0, volume=127. */
    w32_le(out, 0x20, payload_size);
    w32_le(out, 0x24, bank_off);
    w32_le(out, 0x28, 0);
    w32_le(out, 0x2c, 0x7f);

    /* SShd bank header at bank_off (0x30). */
    uint8_t *bank = out + bank_off;
    w32_le(bank, 0x04, payload_size);
    w32_le(bank, 0x0c, HG_BANK_MAGIC);
    w32_le(bank, 0x10, 0x80);        /* table1 offset -> bank+0x30 */
    w32_le(bank, 0x14, 0xffffffffu); /* t2 absent */
    w32_le(bank, 0x18, 0xffffffffu); /* t3 absent */
    w32_le(bank, 0x1c, 0x90);        /* table4 offset -> bank+0x3c */
    w32_le(bank, 0x20, 0xffffffffu);
    w32_le(bank, 0x24, 0xffffffffu);
    w32_le(bank, 0x7c, 0xffffffffu); /* slot state 3 */

    /* Minimal table4 at bank+0x90 supporting lookup4(slot, param1=1, param2=3). */
    uint8_t *t4 = bank + 0x90;
    w16_le(t4, 0x00, 1);             /* max index >= 1 */
    w16_le(t4, 0x02, 0xffff);        /* index 0 unused */
    w16_le(t4, 0x04, 0x10);          /* index 1 -> subtable at t4+0x10 */
    w16_le(t4, 0x10, 3);             /* max extra >= 3 */
    w16_le(t4, 0x12, 0x30);
    w16_le(t4, 0x14, 0x34);
    w16_le(t4, 0x16, 0x38);
    w16_le(t4, 0x18, 0x40);          /* extra 3 -> sequence entry at t4+0x40 */
    w32_le(t4, 0x40, 0x00403ca0u);   /* synthetic cue data marker */

    /* Synthetic ADPCM blocks at payload_off. */
    payload_out[0] = 12; /* filter 0, shift 12 */
    payload_out[1] = 7;  /* loop-start + repeat + end (continuous loop) */
    memset(payload_out + 2, 0x66, 14);
    payload_out[16] = 12; /* filter 0, shift 12 */
    payload_out[17] = 1;  /* end without loop */
    memset(payload_out + 18, 0xe1, 14);
    memcpy(out + payload_off, payload_out, payload_size);
    *out_size = total;
}

static Guest *guest_create(bool route_bank_calls) {
    Guest *g = calloc(1, sizeof(*g));
    assert(g);
    g->ee = calloc(EE_RAM_SIZE, 1);
    g->scratch = calloc(SCRATCH_SIZE, 1);
    assert(g->ee && g->scratch);
    g->route_bank_calls = route_bank_calls;

    g->audio_bus = (HGAudioBus){
        audio_r8, audio_r16, audio_r32,
        audio_w8, audio_w16, audio_w32,
        audio_call, g
    };
    HGSpu2Io io = {g, iop_read, spu_write16, spu_voice_transfer, NULL};
    g->audio_iop = hg_audio_iop_create(io);
    assert(g->audio_iop);
    hg_audio_ee_service_init(&g->audio_ee, &g->audio_bus, g->audio_iop);

    /* Initialize EE audio boot state: SPU2 destination table and free channels. */
    const uint32_t destinations[5] = {
        SPU_DEST_GROUP0, 0x54000u, 0x89000u, 0x1e0000u, 0x71000u
    };
    for (uint32_t i = 0; i < 5; ++i)
        guest_store(g, HG_AUDIO_CTX_SAVE + i * 4, 4, destinations[i]);
    for (uint32_t ch = 0; ch < 32; ++ch)
        guest_store(g, HG_AUDIO_CHANNEL_BASE + ch * HG_CH_STRIDE, 4, UINT32_MAX);

    g->read_env = (HGReadEnv){
        .user = g,
        .read32 = cdvd_read32,
        .sync = cdvd_sync,
        .disk_ready = cdvd_disk_ready,
        .read = cdvd_read,
        .get_error = cdvd_get_error,
    };
    g->title_scene.call_fp = scene_call_fp;
    g->title_scene.scratch_top = SCRIPT_SCRATCH;
    return g;
}

static void guest_destroy(Guest *g) {
    hg_audio_iop_destroy(g->audio_iop);
    g->audio_iop = NULL;
    free(g->scratch);
    free(g->ee);
    free(g);
}

static void stage_pack_for_bank(Guest *g) {
    /* Synthetic file record at 0x003ead20: LBA=10, byte_length=2048. */
    guest_store(g, 0x003ead20u, 4, 10u);
    guest_store(g, 0x003ead24u, 4, 2048u);
    /* PACK header: 1 audio member (counts+0x18 = 1), 0 fixup, 0 extra. */
    guest_store(g, PACK_HEADER + 0x18, 2, 1);
    guest_store(g, PACK_HEADER + 0x1a, 2, 0);
    guest_store(g, PACK_HEADER + 0x1c, 2, 0);
    /* Member 0 descriptor at PACK_HEADER+0x40: {offset, size, member_id, 0}. */
    guest_store(g, PACK_HEADER + 0x40, 4, 0);
    guest_store(g, PACK_HEADER + 0x44, 4, g->bank_blob_size);
    guest_store(g, PACK_HEADER + 0x48, 4, BANK_MEMBER_ID);
    /* Loader task state: phase 0, destination address BANK_LOAD_ADDR. */
    guest_store(g, PACK_TASK + 0x3b, 1, 0);
    guest_store(g, PACK_TASK + 0x48, 4, BANK_LOAD_ADDR);
}

static uint32_t drive_pack_audio_registration(Guest *g, bool step_dma) {
    HGResourceEnv env = make_res_env(g);
    bool saw_busy = false;
    for (unsigned step = 0; step < 24; ++step) {
        if (hg_pack_special_step(&env, PACK_TASK, PACK_HEADER, PACK_HEADER) == 1) {
            assert(!step_dma || saw_busy);
            return guest_load(g, 0x003f4300u + BANK_MEMBER_ID * 4, 4);
        }
        HGSg2Reply reply;
        assert(hg_audio_ee_flush(&g->audio_ee, &reply));
        if (reply.upload_busy) {
            saw_busy = true;
            if (step_dma) {
                assert(hg_audio_iop_step_dma(g->audio_iop));
                assert(hg_audio_ee_flush(&g->audio_ee, &reply));
                assert(reply.upload_busy == 0);
            }
        }
    }
    return 0;
}

static void assert_all_zero(const int16_t *pcm, size_t frames) {
    for (size_t i = 0; i < frames * 2; ++i)
        assert(pcm[i] == 0);
}

/* ---- Test 1: Full supported scene -> audio SFX pipeline & boundary ----- */

static void test_scene_sfx_to_audio_boundary(void) {
    Guest *g = guest_create(true);
    uint8_t payload[32];
    build_synthetic_bank(g->bank_blob, &g->bank_blob_size, payload);
    stage_pack_for_bank(g);

    /* 1. Existing resource loader (hg_pack_special_step) -> 00156a50 -> M22. */
    uint32_t endpoint = drive_pack_audio_registration(g, true);
    uint32_t expected_endpoint = (BANK_LOAD_ADDR + 0x130u + 0x40u) & ~0x3fu;
    assert(endpoint == expected_endpoint);
    assert(g->iop_allocs == 1 && g->iop_frees == 1 && g->iop_alloc_size == 0);
    assert(g->spu_dma_count == 1);

    uint32_t slot = guest_load(g, HG_AUDIO_ID_TABLE + 0 * 0x78, 4);
    assert(slot == 0 && hg_audio_slot_active(&g->audio_bus, slot) == 1);
    uint32_t spu_addr = 0;
    assert(hg_audio_ee_sample_address(&g->audio_ee, slot, 0, &spu_addr));
    assert(spu_addr == SPU_DEST_GROUP0);
    uint8_t uploaded[32];
    assert(hg_audio_iop_read_spu(g->audio_iop, SPU_DEST_GROUP0, uploaded, sizeof(uploaded)));
    assert(memcmp(uploaded, payload, sizeof(payload)) == 0);

    /* 2. Existing title menu (hg_title_menu) emits real 00156ad0 SFX request. */
    guest_store(g, 0x700000c0u, 4, MODE_BLOCK);
    guest_store(g, MODE_BLOCK + 9, 1, 2);           /* title menu input phase */
    guest_store(g, MODE_BLOCK + 0x11, 1, 0);        /* cursor at item 0 */
    guest_store(g, TITLE_ALPHA, 4, 0x43000000u);    /* 128.0f -> menu active */
    guest_store(g, SAVE_FLAG, 4, 1);                /* Continue selectable */
    guest_store(g, VOLUME_ADDR, 4, 0x3f800000u);    /* 1.0f -> volume 127 */
    guest_store(g, PAD_EDGE, 2, 0x4000u);           /* D-pad Down edge */

    HGResourceEnv env = make_res_env(g);
    assert(hg_title_menu(&env) == 0);
    assert(guest_load(g, MODE_BLOCK + 0x11, 1) == 1);
    assert(g->sfx_request_count == 1);
    /* Scene-produced values from src/front_end.c:570 -> sound(e, 4). */
    assert(g->sfx_requests[0].entry == 0x00156ad0u);
    assert(g->sfx_requests[0].a0 == 4u);            /* sound ID 4 (cursor) */
    assert(g->sfx_requests[0].a1 == 0x1000u);       /* default pitch scale */
    assert(g->sfx_requests[0].a2 == 0x7fu);         /* volume 127 */
    assert(g->sfx_requests[0].a3 == 0x40u);         /* center pan */
    assert(g->sfx_requests[0].f12 == 1u);           /* t0 = 1 (direct SFX flag) */

    /* 3. Deliver scene request through documented 00157ed0(4) mapping
     *    (bank_group=0, bank_idx=0, param1=1, param2=3, t0=0) -> hg_audio_play. */
    uint32_t mapped_slot = guest_load(g, HG_AUDIO_ID_TABLE + 0 * 0x78 + 0 * 4, 4);
    assert(mapped_slot == slot);
    uint32_t play_index = hg_audio_play(&g->audio_bus, mapped_slot, 1, 3, 0, 0);
    assert(play_index == 0);
    uint32_t cmd = HG_AUDIO_COMMAND_BASE + play_index * HG_CMD_STRIDE;
    assert(guest_load(g, cmd + HG_CMD_STATE, 4) == 1);
    assert(guest_load(g, cmd + HG_CMD_SLOT, 4) == slot);
    assert(guest_load(g, cmd + HG_CMD_SAMPLE, 4) == BANK_LOAD_ADDR + 0x30u + 0x90u + 0x40u);

    /* 4. Demonstrate last automatic boundary: hg_audio_play alone produces ZERO
     *    SG2IOP packets, ZERO SPU2 writes, and ZERO PCM output because the EE
     *    note sequencer (002ade94..002ae2c0 / 002a96b8 / 002ab508) and physical
     *    voice allocator are not reconstructed. */
    g->spu_write_count = 0;
    HGSg2Reply reply;
    assert(hg_audio_ee_flush(&g->audio_ee, &reply));
    assert(g->spu_write_count == 0);
    for (unsigned v = 0; v < HG_SG2_VOICES; ++v)
        assert(reply.envelope[v] == 0);
    int16_t pcm[128];
    hg_audio_iop_render(g->audio_iop, pcm, 32);
    assert_all_zero(pcm, 32);

    /* 5. Externally supplied resolved note & physical voice -> M22 adapter. */
    const uint32_t physical_voice = 6;
    const uint32_t sample_offset = 0;
    const HGSg2VoiceParams resolved = {
        .note = 60, .root = 60, .scale = 0x116bu,
        .left = 0x2000u, .right = 0x2000u,
        .adsr1 = 0x8080u, .adsr2 = 0x808au,
        .fine_offset = 0, .bend = 64, .bend_scale = 1
    };
    assert(hg_audio_ee_stage_play_voice(&g->audio_ee, play_index, physical_voice,
                                        sample_offset, resolved));
    assert(hg_audio_ee_stage_key(&g->audio_ee, physical_voice, true));

    /* Negative check: before flush, IOP has not received packets -> silence. */
    assert(g->spu_write_count == 0);
    hg_audio_iop_render(g->audio_iop, pcm, 8);
    assert_all_zero(pcm, 8);

    /* Flush RPC -> verify ordered SPU2 register writes & ENVX readiness. */
    assert(hg_audio_ee_flush(&g->audio_ee, &reply));
    assert(reply.upload_busy == 0);
    assert(reply.envelope[physical_voice] == 0x7fffu);
    for (unsigned v = 0; v < HG_SG2_VOICES; ++v)
        if (v != physical_voice) assert(reply.envelope[v] == 0);

    /* Expected SPU2 writes for voice 6: ADSR(2) + SSA(2) + GAIN(2) + PITCH(1) + KEY_ON(4) = 11. */
    assert(g->spu_write_count == 11);
    assert(g->spu_writes[0].address == 0xbf900066u && g->spu_writes[0].value == 0x8080u);
    assert(g->spu_writes[1].address == 0xbf900068u && g->spu_writes[1].value == 0x808au);
    assert(g->spu_writes[2].address == 0xbf900208u && g->spu_writes[2].value == 0x0000u);
    assert(g->spu_writes[3].address == 0xbf90020au && g->spu_writes[3].value == 0x2808u);
    assert(g->spu_writes[4].address == 0xbf900060u && g->spu_writes[4].value == 0x2000u);
    assert(g->spu_writes[5].address == 0xbf900062u && g->spu_writes[5].value == 0x2000u);
    assert(g->spu_writes[6].address == 0xbf900064u && g->spu_writes[6].value > 0);
    assert(g->spu_writes[7].address == 0xbf9001a0u && g->spu_writes[7].value == (1u << 6));
    assert(g->spu_writes[8].address == 0xbf9001a2u && g->spu_writes[8].value == 0);

    /* Render model output: looping synthetic ADPCM block (+6 at gain 0x2000 -> +3). */
    hg_audio_iop_render(g->audio_iop, pcm, 64);
    for (size_t i = 0; i < 64; ++i)
        assert(pcm[2 * i] == 3 && pcm[2 * i + 1] == 3);

    /* 6. Stop / Reset: hg_audio_cancel updates EE command & channel ring only. */
    uint32_t channel = guest_load(g, cmd + HG_CMD_CHANNEL, 4);
    assert(channel < 32);
    assert(hg_audio_cancel(&g->audio_bus, play_index) == 0);
    assert(guest_load(g, cmd + HG_CMD_STATE, 4) == 2);
    assert(guest_load(g, cmd + HG_CMD_SLOT, 4) == UINT32_MAX);
    uint32_t qbase = HG_AUDIO_CHANNEL_QUEUE + channel * HG_CH_STRIDE;
    assert(guest_load(g, qbase + HG_CH_CMD_RING, 4) == 3);
    assert(guest_load(g, qbase + 0, 1) == 0xffu);
    assert(guest_load(g, qbase + 1, 1) == 0x41u);
    assert(guest_load(g, qbase + 2, 1) == 0xf7u);

    /* Cancelled play_index must be rejected by hg_audio_ee_stage_play_voice. */
    assert(!hg_audio_ee_stage_play_voice(&g->audio_ee, play_index, physical_voice,
                                         sample_offset, resolved));

    /* EE cancel does not auto-emit SG2IOP key-off; voice still renders until key-off. */
    hg_audio_iop_render(g->audio_iop, pcm, 8);
    assert(pcm[0] == 3 && pcm[1] == 3);

    /* Explicit key-off + flush silences voice in host model. */
    g->spu_write_count = 0;
    assert(hg_audio_ee_stage_key(&g->audio_ee, physical_voice, false));
    assert(hg_audio_ee_flush(&g->audio_ee, &reply));
    assert(g->spu_write_count == 4);
    assert(g->spu_writes[0].address == 0xbf9001a4u && g->spu_writes[0].value == (1u << 6));
    assert(reply.envelope[physical_voice] == 0);
    hg_audio_iop_render(g->audio_iop, pcm, 32);
    assert_all_zero(pcm, 32);

    /* 7. Teardown and post-teardown fail-closed check. */
    hg_audio_iop_destroy(g->audio_iop);
    g->audio_iop = NULL;
    g->audio_ee.iop = NULL;
    assert(!hg_audio_ee_flush(&g->audio_ee, &reply));
    assert(hg_audio_ee_bank_call(&g->audio_ee, HG_SG2_UPLOAD_POLL, 0, 0, 0) == UINT32_MAX);
    assert(!hg_audio_ee_stage_play_voice(&g->audio_ee, 0, physical_voice, 0, resolved));
    guest_destroy(g);
}

/* ---- Test 2: Title Scene / HGScript voice cue (001564a0/00156550) ------ */

static void publish_synthetic_title_script(Guest *g, uint32_t voice_id) {
    guest_store(g, LOADER_BUSY, 1, 0);
    guest_store(g, NORMAL_ACTIVE, 2, 0);
    guest_store(g, FADE_PHASE, 1, 0);
    guest_store(g, TITLE_HANDLE, 4, TITLE_PARENT);

    /* Fixed FLK5 parent with child 18 = type-12 collection of 1,376 bytes. */
    guest_store(g, TITLE_PARENT, 4, 0x354b4c46u);
    guest_store(g, TITLE_PARENT + 4, 4, 20);
    guest_store(g, TITLE_PARENT + 8, 4, 0x1e00u);
    guest_store(g, TITLE_PARENT + 16 + 18 * 4, 4, 0x0c0c9a00u);
    guest_store(g, TITLE_PARENT + 16 + 19 * 4, 4, 0x010c9f60u);

    /* Record 0: cmd 7 (voice cue at pool+0), cmd 1 (text at pool+12), cmd 6 wait, cmd 0. */
    guest_store(g, TITLE_CHILD + 0, 4, 1);        /* 1 record */
    guest_store(g, TITLE_CHILD + 4, 4, 32);       /* pool offset */
    guest_store(g, TITLE_CHILD + 8, 4, 12);       /* record 0 offset */
    guest_store(g, TITLE_CHILD + 12, 4, (0u << 6) | 7u);  /* voice block at pool+0 */
    guest_store(g, TITLE_CHILD + 16, 4, (3u << 6) | 1u);  /* text block at pool+12 */
    guest_store(g, TITLE_CHILD + 20, 4, (2u << 6) | 6u);  /* wait 1 frame */
    guest_store(g, TITLE_CHILD + 24, 4, 0u);              /* terminate */

    /* Pool at TITLE_CHILD + 32: */
    guest_store(g, TITLE_CHILD + 32, 4, voice_id);        /* pool+0: voice ID */
    guest_store(g, TITLE_CHILD + 36, 4, UINT32_MAX);      /* pool+4: no cue list */
    guest_store(g, TITLE_CHILD + 44, 4, 16);              /* pool+12: text width */
    guest_store(g, TITLE_CHILD + 48, 1, 'O');             /* pool+16: "OK\0" */
    guest_store(g, TITLE_CHILD + 49, 1, 'K');
    guest_store(g, TITLE_CHILD + 50, 1, 0);
}

static void test_hgscript_dialogue_voice_boundary(void) {
    Guest *g = guest_create(true);
    publish_synthetic_title_script(g, 0x240u);
    guest_store(g, 0x700000c0u, 4, MODE_BLOCK);
    guest_store(g, 0x700000c4u, 4, 1); /* normal display mode */

    HGResourceEnv env = make_res_env(g);
    uint32_t res = 0;

    /* 00a88b40 phase 0 -> fade-in setup; phase 1 -> hg_title_script_start. */
    assert(hg_title_scene_call(&env, &g->title_scene, 0x00a88b40u, TITLE_TASK, &res) == 1);
    assert(res == 1 && guest_load(g, TITLE_TASK + 5, 1) == 1);
    assert(hg_title_scene_call(&env, &g->title_scene, 0x00a88b40u, TITLE_TASK, &res) == 1);
    assert(g->title_scene.dialogue.parent == TITLE_PARENT);

    /* First 0025c170 tick emits real 001564a0(1, 0x240, 1, 0, 1.0f, 0.02f) and
     * blocks waiting for VOICE_STATE (003f2fa0) == 3 without drawing glyphs. */
    assert(hg_title_scene_call(&env, &g->title_scene, 0x0025c170u, 0, &res) == 1);
    assert(g->voice_start_count == 1);
    assert(g->voice_starts[0].entry == 0x001564a0u);
    assert(g->voice_starts[0].a0 == 1u && g->voice_starts[0].a1 == 0x240u);
    assert(g->voice_starts[0].a2 == 1u && g->voice_starts[0].a3 == 0u);
    assert(g->voice_starts[0].f12 == 0x3f800000u && g->voice_starts[0].f13 == 0x3ca3d70au);
    assert(g->glyph_draw_count == 0);

    /* Verify 001564a0 does NOT enter M22's SShd command queue or SG2IOP. */
    assert(guest_load(g, HG_AUDIO_COMMAND_BASE + HG_CMD_STATE, 4) == 0);
    assert(guest_load(g, HG_SG2_EE_CURSOR, 4) == 0);

    /* Negative control: without readiness signal, script remains blocked. */
    assert(hg_title_scene_call(&env, &g->title_scene, 0x0025c170u, 0, &res) == 1);
    assert(g->glyph_draw_count == 0);

    /* Signal external streaming-voice readiness (VOICE_STATE = 3). */
    guest_store(g, VOICE_STATE, 1, 3);
    assert(hg_title_scene_call(&env, &g->title_scene, 0x0025c170u, 0, &res) == 1);
    assert(guest_load(g, VOICE_STATE, 1) == 2);
    assert(g->glyph_draw_count == 1);

    /* Player skip + fade phase 2 -> hg_title_script_release -> 00156550 stop. */
    guest_store(g, PAD_EDGE, 2, 0x20u);
    assert(hg_title_scene_call(&env, &g->title_scene, 0x00a88b40u, TITLE_TASK, &res) == 1);
    assert(guest_load(g, TITLE_TASK + 5, 1) == 2);
    guest_store(g, FADE_PHASE, 1, 2);
    assert(hg_title_scene_call(&env, &g->title_scene, 0x00a88b40u, TITLE_TASK, &res) == 1);
    assert(res == 0 && g->title_scene.dialogue.parent == 0);
    assert(g->voice_stop_count == 1);

    /* Negative control: revoked title handle suppresses stale voice stop. */
    guest_store(g, TITLE_TASK + 5, 1, 1);
    guest_store(g, TITLE_TASK + 6, 1, 0);
    guest_store(g, FADE_PHASE, 1, 0);
    guest_store(g, PAD_EDGE, 2, 0);
    assert(hg_title_script_start(&env, scene_call_fp, &g->title_scene.dialogue, TITLE_TASK) == 1);
    guest_store(g, TITLE_HANDLE, 4, 0); /* handle invalidated by area load */
    hg_title_script_release(&env, &g->title_scene.dialogue);
    assert(g->title_scene.dialogue.parent == 0);
    assert(g->voice_stop_count == 1); /* unchanged: stale stop suppressed */

    guest_destroy(g);
}

/* ---- Test 3: Negative controls for disconnected routing & lifecycle ---- */

static void test_negative_controls(void) {
    const HGSg2VoiceParams resolved = {
        .note = 60, .root = 60, .scale = 0x116bu,
        .left = 0x2000u, .right = 0x2000u,
        .adsr1 = 0x8080u, .adsr2 = 0x808au,
        .fine_offset = 0, .bend = 64, .bend_scale = 1
    };

    /* NC1: Disconnected bank-call routing (002a7560/002a7590/002b5428 not
     * routed to hg_audio_ee_bank_call) -> staging play voice MUST fail. */
    {
        Guest *g = guest_create(false);
        uint8_t payload[32];
        build_synthetic_bank(g->bank_blob, &g->bank_blob_size, payload);
        stage_pack_for_bank(g);
        uint32_t endpoint = drive_pack_audio_registration(g, false);
        assert(endpoint != 0);
        assert(g->spu_dma_count == 0);
        uint32_t slot = guest_load(g, HG_AUDIO_ID_TABLE, 4);
        uint32_t play_index = hg_audio_play(&g->audio_bus, slot, 1, 3, 0, 0);
        assert(play_index == 0);
        assert(!hg_audio_ee_stage_play_voice(&g->audio_ee, play_index, 6, 0, resolved));
        assert(g->spu_write_count == 0);
        int16_t pcm[32];
        hg_audio_iop_render(g->audio_iop, pcm, 16);
        assert_all_zero(pcm, 16);
        guest_destroy(g);
    }

    /* NC2: Missing DMA step -> poll stays busy, loader stays parked, staging fails. */
    {
        Guest *g = guest_create(true);
        uint8_t payload[32];
        build_synthetic_bank(g->bank_blob, &g->bank_blob_size, payload);
        stage_pack_for_bank(g);
        uint32_t endpoint = drive_pack_audio_registration(g, false);
        assert(endpoint == 0);
        assert(hg_audio_ee_bank_call(&g->audio_ee, HG_SG2_UPLOAD_POLL, 0, 0, 0) == 1);
        uint32_t slot = guest_load(g, HG_AUDIO_ID_TABLE, 4);
        uint32_t play_index = hg_audio_play(&g->audio_bus, slot, 1, 3, 0, 0);
        assert(play_index == 0);
        assert(!hg_audio_ee_stage_play_voice(&g->audio_ee, play_index, 6, 0, resolved));
        guest_destroy(g);
    }

    /* NC3: Clearing registered bank slot invalidates active play staging. */
    {
        Guest *g = guest_create(true);
        uint8_t payload[32];
        build_synthetic_bank(g->bank_blob, &g->bank_blob_size, payload);
        stage_pack_for_bank(g);
        assert(drive_pack_audio_registration(g, true) != 0);
        uint32_t slot = guest_load(g, HG_AUDIO_ID_TABLE, 4);
        uint32_t play_index = hg_audio_play(&g->audio_bus, slot, 1, 3, 0, 0);
        assert(play_index == 0);
        hg_audio_slot_clear(&g->audio_bus, slot);
        assert(!hg_audio_ee_stage_play_voice(&g->audio_ee, play_index, 6, 0, resolved));
        guest_destroy(g);
    }

    /* NC4: Zero-initialized (unbound) HGAudioEeService fails closed cleanly. */
    {
        HGAudioEeService unbound = {0};
        HGSg2Reply reply = {0};
        uint32_t addr = 0;
        assert(!hg_audio_ee_post(&unbound, (HGSg2Packet){HG_SG2_NOP, 0, 0, 0}));
        assert(!hg_audio_ee_flush(&unbound, &reply));
        assert(hg_audio_ee_bank_call(&unbound, HG_SG2_UPLOAD_POLL, 0, 0, 0) == UINT32_MAX);
        assert(!hg_audio_ee_sample_address(&unbound, 0, 0, &addr));
        assert(!hg_audio_ee_stage_voice(&unbound, 0, 0, 0, resolved));
        assert(!hg_audio_ee_stage_play_voice(&unbound, 0, 0, 0, resolved));
        assert(!hg_audio_ee_stage_key(&unbound, 0, true));
    }
}

int main(void) {
    test_scene_sfx_to_audio_boundary();
    test_hgscript_dialogue_voice_boundary();
    test_negative_controls();
    return 0;
}
